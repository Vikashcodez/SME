import { z } from 'zod';

export const createCustomerSchema = z.object({
    customer_code: z.string().optional(),
    customer_name: z.string().min(2).max(255),
    contact_person: z.string().optional(),
    email: z.string().email().optional().or(z.literal('')),
    phone: z.string().max(30).optional(),
    mobile: z.string().max(30).optional(),
    gstin: z.string().regex(/^[0-9]{2}[A-Z]{5}[0-9]{4}[A-Z]{1}[1-9A-Z]{1}Z[0-9A-Z]{1}$/).optional().or(z.literal('')),
    pan: z.string().regex(/^[A-Z]{5}[0-9]{4}[A-Z]{1}$/).optional().or(z.literal('')),
    currency: z.string().optional(),
    billing_address: z.string().optional(),
    billing_city: z.string().optional(),
    billing_state: z.string().optional(),
    billing_state_code: z.string().optional(),
    billing_pincode: z.string().optional(),
    shipping_address: z.string().optional(),
    shipping_city: z.string().optional(),
    shipping_state: z.string().optional(),
    shipping_state_code: z.string().optional(),
    shipping_pincode: z.string().optional(),
    credit_limit: z.number().nonnegative().optional(),
    credit_days: z.number().int().nonnegative().optional(),
    payment_terms: z.string().optional(),
}).passthrough();

export const createSalesOrderSchema = z.object({
    customer_id: z.number().int().positive(),
    order_number: z.string().optional(),
    order_date: z.string().or(z.date()).optional(),
    delivery_date: z.string().or(z.date()).optional().nullable(),
    quotation_id: z.number().optional().nullable(),
    customer_po_number: z.string().optional().nullable(),
    customer_po_date: z.string().or(z.date()).optional().nullable(),
    payment_terms: z.string().optional(),
    place_of_supply: z.string().optional(),
    remarks: z.string().optional().nullable(),
    status: z.string().optional(),
    items: z.array(z.object({
        product_id: z.number().optional().nullable(),
        item_name: z.string().min(1),
        hsn_code: z.string().optional().nullable(),
        quantity: z.number().positive(),
        uom: z.string().optional(),
        unit_price: z.number().nonnegative(),
        discount_amount: z.number().nonnegative().optional(),
        gst_rate: z.number().min(0).max(100),
    })).min(1),
}).passthrough();
